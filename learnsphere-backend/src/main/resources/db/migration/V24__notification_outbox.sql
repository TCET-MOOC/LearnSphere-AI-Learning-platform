-- V24: Notification event catalogue outbox and performance indexes
-- Implements W5-06, A-17, [E-F14]

CREATE TABLE public.notification_outbox (
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type character varying(50) NOT NULL,
    aggregate_type character varying(50) NOT NULL,
    aggregate_id character varying(100) NOT NULL,
    recipient_id bigint NOT NULL,
    title character varying(255) NOT NULL,
    body text NOT NULL,
    payload text,
    status character varying(20) NOT NULL DEFAULT 'PENDING',
    created_at timestamp(6) without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    processed_at timestamp(6) without time zone,
    retry_count integer NOT NULL DEFAULT 0,
    error_message text,
    CONSTRAINT fk_outbox_recipient FOREIGN KEY (recipient_id) REFERENCES public.users(user_id) ON DELETE CASCADE,
    CONSTRAINT uq_outbox_event_aggregate_recipient UNIQUE (event_type, aggregate_id, recipient_id)
);

CREATE INDEX idx_outbox_status_created_at ON public.notification_outbox (status, created_at);
CREATE INDEX idx_outbox_recipient_id ON public.notification_outbox (recipient_id);

CREATE INDEX IF NOT EXISTS idx_notifications_user_created ON public.notifications (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_notifications_user_read ON public.notifications (user_id, read);

