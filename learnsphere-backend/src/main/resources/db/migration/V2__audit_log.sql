-- W1-11: append-only audit history and a unique user-role assignment.
--
-- audit_log is written by role/status changes (PLAN 6.10). It has no update or
-- delete API; before_json/after_json store only the fields needed to explain
-- the change. The unique index closes the duplicate-role gap before the admin
-- role endpoints are hardened.

CREATE TABLE audit_log (
    id bigint NOT NULL,
    actor_id bigint,
    action character varying(100) NOT NULL,
    resource_type character varying(50) NOT NULL,
    resource_id bigint,
    before_json jsonb,
    after_json jsonb,
    ip character varying(45),
    created_at timestamp(6) without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE audit_log ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.audit_log_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY audit_log
    ADD CONSTRAINT audit_log_pkey PRIMARY KEY (id);

ALTER TABLE ONLY audit_log
    ADD CONSTRAINT audit_log_actor_id_fkey FOREIGN KEY (actor_id)
    REFERENCES users(user_id) ON DELETE SET NULL;

CREATE INDEX idx_audit_log_actor ON audit_log (actor_id);
CREATE INDEX idx_audit_log_resource ON audit_log (resource_type, resource_id);
CREATE INDEX idx_audit_log_created_at ON audit_log (created_at);

-- A role can be assigned to a user once. Keep the oldest row if a legacy
-- database already contains duplicates, then enforce the invariant.
DELETE FROM user_roles duplicate
USING user_roles keeper
WHERE duplicate.user_role_id > keeper.user_role_id
  AND duplicate.user_id = keeper.user_id
  AND duplicate.role_id = keeper.role_id;

CREATE UNIQUE INDEX ux_user_roles_user_role ON user_roles (user_id, role_id);
