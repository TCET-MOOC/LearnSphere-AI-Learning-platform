-- V3__refresh_tokens.sql
-- Table to persist refresh tokens for rotation, replay attack detection, and family revocation (W1-05, M-08)

CREATE TABLE IF NOT EXISTS refresh_tokens (
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    user_id bigint NOT NULL,
    token character varying(255) NOT NULL,
    family_id character varying(64) NOT NULL,
    status character varying(20) NOT NULL DEFAULT 'ACTIVE',
    replaced_by_token character varying(255),
    expires_at timestamp(6) without time zone NOT NULL,
    created_at timestamp(6) without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT refresh_tokens_pkey PRIMARY KEY (id),
    CONSTRAINT ux_refresh_tokens_token UNIQUE (token),
    CONSTRAINT refresh_tokens_user_id_fkey FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_refresh_tokens_user_id ON refresh_tokens (user_id);
CREATE INDEX IF NOT EXISTS idx_refresh_tokens_family_id ON refresh_tokens (family_id);
CREATE INDEX IF NOT EXISTS idx_refresh_tokens_expires_at ON refresh_tokens (expires_at);
CREATE INDEX IF NOT EXISTS idx_refresh_tokens_status ON refresh_tokens (status);
