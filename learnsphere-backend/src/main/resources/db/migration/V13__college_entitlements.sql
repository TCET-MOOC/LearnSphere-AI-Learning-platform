-- V13: College entitlements table with unique (student_id, course_id) and affiliation_requests status index (M-09, A-20, A-24)

CREATE TABLE IF NOT EXISTS public.college_entitlements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL,
    course_id BIGINT NOT NULL,
    college_id BIGINT,
    grant_type VARCHAR(50) NOT NULL DEFAULT 'SAME_COLLEGE',
    granted_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    granted_by BIGINT,
    revoked BOOLEAN NOT NULL DEFAULT FALSE,
    revoked_at TIMESTAMP WITHOUT TIME ZONE,
    revoked_by BIGINT,
    reason TEXT,
    CONSTRAINT fk_college_entitlements_student FOREIGN KEY (student_id) REFERENCES public.users(user_id) ON DELETE CASCADE,
    CONSTRAINT fk_college_entitlements_course FOREIGN KEY (course_id) REFERENCES public.courses(id) ON DELETE CASCADE,
    CONSTRAINT fk_college_entitlements_college FOREIGN KEY (college_id) REFERENCES public.colleges(id) ON DELETE SET NULL,
    CONSTRAINT fk_college_entitlements_granted_by FOREIGN KEY (granted_by) REFERENCES public.users(user_id) ON DELETE SET NULL,
    CONSTRAINT fk_college_entitlements_revoked_by FOREIGN KEY (revoked_by) REFERENCES public.users(user_id) ON DELETE SET NULL,
    CONSTRAINT uq_college_entitlements_student_course UNIQUE (student_id, course_id)
);

CREATE INDEX IF NOT EXISTS idx_college_entitlements_student_course
    ON public.college_entitlements(student_id, course_id);

CREATE INDEX IF NOT EXISTS idx_college_entitlements_college
    ON public.college_entitlements(college_id);

CREATE INDEX IF NOT EXISTS idx_affiliation_requests_status
    ON public.affiliation_requests(status);
